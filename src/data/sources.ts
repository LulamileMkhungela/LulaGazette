export function getSourceById(id: string): ExternalSource | undefined {
  return externalSources.find((s) => s.id === id);
}

export function getSourcesByCountry(countryCode?: string): ExternalSource[] {
  if (!countryCode || countryCode === "all" || countryCode === "AU") {
    return externalSources;
  }
  const code = countryCode.toUpperCase();
  return externalSources.filter((s) => s.countryCode === code || s.countryCode === "AU");
}
