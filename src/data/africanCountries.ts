export function getAllCountries(): AfricanCountry[] {
  return africanCountries;
}

export function getCountryByCode(code?: string): AfricanCountry | undefined {
  if (!code) return undefined;
  const upper = code.toUpperCase();
  return africanCountries.find((c) => c.code === upper || c.code3 === upper);
}

export function getCountriesByRegion(region: AfricanRegion): AfricanCountry[] {
  return africanCountries.filter((c) => c.region === region);
}

export function getCountryFlag(code?: string): string {
  const c = getCountryByCode(code);
  return c ? c.flag : "🌍";
}

export function getCountryName(code?: string): string {
  const c = getCountryByCode(code);
  return c ? c.name : "Pan-African (All Countries)";
}
